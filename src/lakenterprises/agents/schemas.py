"""Pydantic schemas and typed definitions for Phase 9 specialist agents."""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field


def _now_utc() -> datetime:
    return datetime.now(timezone.utc)


class AgentRole(str, Enum):
    """Specialist agent roles within the multi-agent system."""

    SUPERVISOR = "supervisor"
    DOCUMENT_ANALYST = "document_analyst"
    COMPLIANCE = "compliance"
    KNOWLEDGE_RETRIEVER = "knowledge_retriever"
    RESPONSE_DRAFTER = "response_drafter"
    ESCALATION_HANDOFF = "escalation_handoff"


class AgentTaskStatus(str, Enum):
    """Execution status of an agent subtask."""

    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    NEEDS_REVIEW = "needs_review"
    ESCALATED = "escalated"


class AgentTask(BaseModel):
    """Specification of work assigned to a specialist agent."""

    task_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    process_id: Optional[str] = None
    role: AgentRole
    instruction: str
    context: Dict[str, Any] = Field(default_factory=dict)
    parameters: Dict[str, Any] = Field(default_factory=dict)
    timeout_seconds: float = 60.0
    created_at: datetime = Field(default_factory=_now_utc)


class AgentResult(BaseModel):
    """Standardized output returned by any specialist agent."""

    task_id: str
    role: AgentRole
    status: AgentTaskStatus = AgentTaskStatus.COMPLETED
    output_data: Dict[str, Any] = Field(default_factory=dict)
    reasoning: str = ""
    citations: List[str] = Field(default_factory=list)
    confidence_score: float = Field(default=1.0, ge=0.0, le=1.0)
    metrics: Dict[str, Any] = Field(default_factory=dict)  # tokens, latency_ms
    error: Optional[str] = None


# ── Domain-Specific Agent Schemas ─────────────────────────────────────


class SupervisorPlan(BaseModel):
    """Plan generated by the Supervisor/Orchestrator agent."""

    goal: str
    next_agent: Optional[AgentRole] = None
    planned_agents: List[AgentRole] = Field(default_factory=list)
    subtasks: List[Dict[str, Any]] = Field(default_factory=list)
    is_complete: bool = False
    final_summary: Optional[str] = None


class DocumentAnalysisResult(BaseModel):
    """Analysis produced by the Document Analyst agent."""

    document_id: Optional[str] = None
    document_type: str = "generic"
    key_findings: List[str] = Field(default_factory=list)
    extracted_entities: Dict[str, Any] = Field(default_factory=dict)
    risk_signals: List[str] = Field(default_factory=list)
    confidence: float = 1.0


class ComplianceViolation(BaseModel):
    """Individual policy infraction detected by the Compliance agent."""

    rule_id: str
    rule_name: str
    description: str
    severity: str = "HIGH"  # LOW, MEDIUM, HIGH, CRITICAL
    clause_reference: Optional[str] = None


class ComplianceResult(BaseModel):
    """Evaluation result produced by the Compliance Check agent."""

    is_compliant: bool
    policy_name: str
    violations: List[ComplianceViolation] = Field(default_factory=list)
    recommendation: str = ""
    risk_level: str = "LOW"


class RetrievedFact(BaseModel):
    """Individual grounded evidence retrieved by the Knowledge Retrieval agent."""

    source: str
    locator: str
    snippet: str
    relevance_score: float = 1.0
    citation_id: str


class KnowledgeRetrievalResult(BaseModel):
    """Output from the Knowledge Retrieval agent."""

    query: str
    facts: List[RetrievedFact] = Field(default_factory=list)
    citations: List[str] = Field(default_factory=list)
    coverage_assessment: str = "complete"


class ResponseDraftResult(BaseModel):
    """Communication draft produced by the Response Drafting agent."""

    draft_text: str
    recipient: str = "customer"
    tone: str = "professional"
    citations: List[str] = Field(default_factory=list)
    key_points: List[str] = Field(default_factory=list)
    actions_proposed: List[str] = Field(default_factory=list)


class EscalationHandoffResult(BaseModel):
    """Decision packet produced by the Escalation and Handoff agent."""

    requires_human: bool
    severity: str = "LOW"  # LOW, MEDIUM, HIGH, CRITICAL
    target_role: str = "analyst"  # analyst, manager, admin
    escalation_reason: str = ""
    recommended_actions: List[str] = Field(default_factory=list)
    incident_ticket_id: Optional[str] = None
